// 노드 하나가 이번 틱에 돌려주는 답.
//
// 상태머신은 "지금 어느 상태인가"라는 하나의 값으로 모든 것을 이야기했다. 행동 트리는
// 그런 값을 갖지 않는다 — 매 틱 뿌리에서 다시 내려오면서 각 노드가 이 셋 중 하나로 답하고,
// 그 답이 모여 "이번 프레임에 무엇을 할지"가 정해진다.
public enum BTStatus
{
    // 할 일을 끝냈다. 부모 시퀀스는 다음 자식으로 넘어가고, 셀렉터는 여기서 멈춘다.
    Success,

    // 지금은 할 수 없다(조건이 안 맞거나 대상이 없다). 부모 셀렉터는 다음 후보를 본다.
    Failure,

    // 아직 하는 중이다. 다음 틱에도 이 노드로 돌아온다 — 예전 상태의 Update가 계속 돌던 자리다.
    Running,
}
