// 어느 상태에 있든 성립하면 하던 일을 끊고 넘어가는 전이.
//
// 계층형 상태머신(HFSM)의 부모 상태 전이가 하는 일을, 계층 없이 그 부분만 가져온 것이다.
// 이 프로젝트에 계층을 두지 않은 이유:
//  - 계층의 본래 값어치는 같은 서브트리를 여러 상위 문맥에서 재사용하는 것인데
//    (예: Movement 서브트리를 Patrol 밑에도 Combat 밑에도), 여기는 문맥이 전투 하나뿐이다.
//  - 직업별 차이는 상태 구조가 아니라 데이터로 갈린다(사거리, canHealAllies, ShouldKeepDistance).
//    상태 파일 어디에도 직업 분기가 없다. 즉 갈라 놓을 서브트리 자체가 없다.
//  - 반면 계층을 넣으면 상태가 하나가 아니라 경로가 되어, 전이마다 공통 조상을 찾아
//    거슬러 올라갔다 내려오는 계산이 붙고 "지금 어느 상태인가"가 스택 조회가 된다.
//
// 그래서 실제로 필요한 것 — "모든 상태에 공통으로 걸리는 전이를 한 곳에 모으기" — 만 남겼다.
//
// 구현체는 상태를 갖지 않으므로 모든 유닛이 같은 인스턴스를 공유한다(유닛마다 만들 필요가 없다).
public abstract class GlobalTransition<TContext>
{
    // 넘어갈 상태를 돌려준다. 넘어갈 이유가 없으면 null.
    // currentState를 받는 이유: "이미 그 상태면 다시 걸지 않는다"를 표현하기 위해서다.
    public abstract IState<TContext> Evaluate(TContext context, IState<TContext> currentState);
}
